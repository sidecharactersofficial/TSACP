"""Generate environment/requirements.lock from the installed interpreter.

Resolves the direct pins in requirements.txt together with their transitive
dependency closure of *installed* distributions and writes a sorted pinned
lock file. Run inside the reproduction environment:

    python scripts/gen_lock.py
"""
import importlib.metadata as md
import os
import sys

try:
    from packaging.markers import default_environment
    from packaging.requirements import Requirement
except ImportError:  # pragma: no cover - packaging ships with pip/setuptools
    sys.exit("packaging is required (pip install packaging)")

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REQUIREMENTS = os.path.join(PROJECT_ROOT, "requirements.txt")
OUT = os.path.join(PROJECT_ROOT, "environment", "requirements.lock")

DIRECT = [
    "torch", "numpy", "pandas", "pyarrow", "scipy", "scikit-learn",
    "xgboost", "joblib", "PyYAML", "matplotlib", "seaborn", "tqdm", "pytest",
]


def norm(name):
    return name.lower().replace("_", "-").replace(".", "-")


def main():
    env = default_environment()
    byname = {norm(d.metadata["Name"]): d for d in md.distributions() if d.metadata["Name"]}
    seen = {}
    queue = [norm(x) for x in DIRECT]
    while queue:
        name = queue.pop(0)
        if name in seen or name not in byname:
            continue
        dist = byname[name]
        seen[name] = dist.version
        try:
            reqs = dist.requires or []
        except Exception:
            reqs = []
        for raw in reqs:
            try:
                req = Requirement(raw)
            except Exception:
                continue
            if req.marker and not req.marker.evaluate(env):
                continue
            queue.append(norm(req.name))

    missing = [norm(x) for x in DIRECT if norm(x) not in seen]
    if missing:
        sys.exit(f"missing direct deps: {missing}")

    header = (
        "# Fully resolved dependency lock for the TASCP artifact.\n"
        "# Generated by scripts/gen_lock.py from requirements.txt.\n"
        "# Install: pip install -r environment/requirements.lock\n"
        "# The nvidia-* CUDA packages are transitive deps of the CUDA torch build;\n"
        "# they may be omitted on a CPU-only host.\n"
    )
    lines = [f"{k}=={seen[k]}" for k in sorted(seen)]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(header + "\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} packages)")


if __name__ == "__main__":
    main()
